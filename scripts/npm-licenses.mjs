#!/usr/bin/env node
// Third-party notices for the JavaScript that ends up in the app window, plus the license allowlist check.
//   node scripts/npm-licenses.mjs            write apps/desktop/src-tauri/licenses/THIRD_PARTY_NOTICES-npm.txt
//   node scripts/npm-licenses.mjs --check    fail on a license outside the allowlist, or if the file is stale
// The package set is the production dependency tree of apps/desktop, minus build-time-only branches (see BUILD_ONLY).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const desktop = join(root, "apps/desktop");
const output = join(desktop, "src-tauri/licenses/THIRD_PARTY_NOTICES-npm.txt");

// Licenses we accept in the shipped bundle. Anything else fails CI until it is reviewed and added here.
export const ALLOWED = new Set([
  "0BSD",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "ISC",
  "MIT",
  "MIT-0",
  "OFL-1.1", // the Inter and Newsreader font files
  "Unlicense",
]);

// Per-platform native builds (`@napi-rs/canvas-darwin-arm64`): which one is installed depends on the machine.
const PLATFORM_BINARY = /-(darwin|linux|win32|android|freebsd)-/;

// Branches of the dependency tree that run at build time and are not in the shipped bundle, as "parent > child".
// `@tailwindcss/vite` is listed under `dependencies` but only runs inside vite; the Lingui macro plugin is a
// compile-time Babel plugin.
const BUILD_ONLY = new Set([
  "@tailwindcss/vite",
  "@lingui/core > @lingui/babel-plugin-lingui-macro",
]);

/** Splits "A OR B" / "(A AND B)" into its terms; the app may use any term of an OR, so one allowed term is enough. */
export function licenseAllowed(expression) {
  const text = expression.replace(/[()]/g, "").trim();
  if (text.includes(" AND ")) return text.split(" AND ").every((t) => licenseAllowed(t));
  return text.split(" OR ").some((t) => ALLOWED.has(t.trim()));
}

function collect() {
  const raw = execFileSync("pnpm", ["list", "--prod", "--depth", "Infinity", "--json"], {
    cwd: desktop,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  const project = JSON.parse(raw).find((p) => p.name === "@cadabracraft/desktop");
  const packages = new Map();
  const walk = (deps, parent) => {
    for (const [name, info] of Object.entries(deps ?? {})) {
      if (info.version?.startsWith("link:")) continue; // our own workspace packages
      if (BUILD_ONLY.has(parent ? `${parent} > ${name}` : name)) continue;
      // Optional native packages for other platforms are not installed here; skipping them keeps the output the same on every OS.
      if (!existsSync(join(info.path, "package.json")) || PLATFORM_BINARY.test(name)) continue;
      const key = `${name}@${info.version}`;
      if (!packages.has(key)) {
        packages.set(key, { name, version: info.version, path: info.path });
        walk(info.dependencies, name);
      }
    }
  };
  walk(project.dependencies, "");
  return [...packages.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

function describe(pkg) {
  const manifest = JSON.parse(readFileSync(join(pkg.path, "package.json"), "utf8"));
  const license =
    typeof manifest.license === "string"
      ? manifest.license
      : (manifest.license?.type ?? manifest.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");
  const file = readdirSync(pkg.path).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  const text = file ? readFileSync(join(pkg.path, file), "utf8").trim() : null;
  const repo =
    typeof manifest.repository === "string"
      ? manifest.repository
      : (manifest.repository?.url ?? null);
  return { ...pkg, license, text, repo: repo?.replace(/^git\+/, "").replace(/\.git$/, "") ?? null };
}

function render(packages) {
  const texts = new Map(); // hash -> { text, users }
  for (const p of packages) {
    if (!p.text) continue;
    const hash = createHash("sha256").update(p.text.replace(/\s+/g, " ")).digest("hex");
    if (!texts.has(hash)) texts.set(hash, { text: p.text, users: [] });
    texts.get(hash).users.push(`${p.name}@${p.version}`);
  }
  const lines = [
    "CadabraCraft third-party notices: JavaScript packages",
    "======================================================",
    "",
    "The app window runs the packages below. Each keeps its own license. Generated by scripts/npm-licenses.mjs;",
    "do not edit by hand.",
    "",
    "Packages",
    "--------",
  ];
  for (const p of packages) {
    lines.push(`${p.name}@${p.version}  (${p.license})${p.repo ? `  ${p.repo}` : ""}`);
  }
  lines.push("", "License texts", "-------------");
  for (const { text, users } of texts.values()) {
    lines.push("", `Used by: ${users.join(", ")}`, "", text, "", "-".repeat(40));
  }
  const missing = packages.filter((p) => !p.text).map((p) => `${p.name}@${p.version}`);
  if (missing.length) {
    lines.push(
      "",
      "Packages whose license file is not in the package (the license named above applies):",
      ...missing.map((m) => `  ${m}`),
    );
  }
  return `${lines.join("\n")}\n`.replace(/\r\n/g, "\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const packages = collect().map(describe);
  const bad = packages.filter((p) => !licenseAllowed(p.license));
  if (bad.length) {
    console.error("npm-licenses: license not on the allowlist:");
    for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`);
    process.exit(1);
  }
  const text = render(packages);
  if (process.argv.includes("--check")) {
    if (!existsSync(output) || readFileSync(output, "utf8") !== text) {
      console.error(
        "npm-licenses: THIRD_PARTY_NOTICES-npm.txt is out of date; run node scripts/npm-licenses.mjs",
      );
      process.exit(1);
    }
    console.log(`npm-licenses: ${packages.length} packages ok`);
  } else {
    writeFileSync(output, text);
    console.log(`npm-licenses: wrote ${packages.length} packages`);
  }
}
