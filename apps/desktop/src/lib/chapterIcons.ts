import {
  Anchor,
  Bird,
  BookOpen,
  Castle,
  CloudLightning,
  Compass,
  Crown,
  Eye,
  Feather,
  Flag,
  Flame,
  Gem,
  Ghost,
  Heart,
  Key,
  Leaf,
  Map,
  Moon,
  Mountain,
  Music,
  Scroll,
  Shield,
  Ship,
  Skull,
  Star,
  Sun,
  Swords,
  Trees,
  WandSparkles,
  type LucideIcon,
} from "lucide-react";
import { isEntryIcon, type EntryIcon } from "@cadabracraft/format";

/** Component of each allowed icon name (`ENTRY_ICONS` in the format package). Only these are imported, so the bundle stays small. */
export const COMPONENTS: Record<EntryIcon, LucideIcon> = {
  "book-open": BookOpen,
  feather: Feather,
  scroll: Scroll,
  map: Map,
  compass: Compass,
  anchor: Anchor,
  ship: Ship,
  mountain: Mountain,
  trees: Trees,
  leaf: Leaf,
  sun: Sun,
  moon: Moon,
  "cloud-lightning": CloudLightning,
  flame: Flame,
  star: Star,
  heart: Heart,
  skull: Skull,
  ghost: Ghost,
  eye: Eye,
  key: Key,
  gem: Gem,
  crown: Crown,
  castle: Castle,
  shield: Shield,
  swords: Swords,
  "wand-sparkles": WandSparkles,
  bird: Bird,
  flag: Flag,
  music: Music,
};

/** The component for a stored icon name; undefined for no icon or a name this app does not know (written by a newer one). */
export const iconComponent = (name: string | undefined): LucideIcon | undefined =>
  isEntryIcon(name) ? COMPONENTS[name] : undefined;
